//! Replace one account's generated table without erasing another account's bake.
use color_eyre::{
    Result,
    eyre::{ensure, eyre},
};
use std::{collections::BTreeMap, path::Path};

mod lock;

type Rows<'a> = BTreeMap<&'a str, &'a str>;

pub fn write(path: &Path, account: &str, table: &str) -> Result<()> {
    let _lock = lock::WriteLock::acquire(path)?;
    let previous = match std::fs::read_to_string(path) {
        Ok(previous) => previous,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => String::new(),
        Err(error) => return Err(error.into()),
    };
    let table = merge(&previous, account, table)?;
    let temporary = path.with_extension("rs.tmp");
    std::fs::write(&temporary, table)?;
    std::fs::rename(temporary, path)?;
    Ok(())
}

fn merge(previous: &str, account: &str, replacement: &str) -> Result<String> {
    let (prefix, incoming) = parse(replacement)?;
    let key_prefix = format!("mt5:{account}:");
    ensure!(!incoming.is_empty(), "replacement MT5 table is empty");
    ensure!(
        incoming.keys().all(|key| key.starts_with(&key_prefix)),
        "replacement MT5 table includes a different account"
    );
    let (provenance, mut merged) = if previous.is_empty() {
        (String::new(), BTreeMap::new())
    } else {
        let (old_prefix, mut rows) = parse(previous)?;
        rows.retain(|key, _| !key.starts_with(&key_prefix));
        (preserved_provenance(old_prefix, account), rows)
    };
    merged.extend(incoming);
    let rows = merged.values().copied().collect::<Vec<_>>().join("\n");
    Ok(format!("{provenance}{prefix} = &[\n{rows}\n];\n"))
}

fn parse(table: &str) -> Result<(&str, Rows<'_>)> {
    let (prefix, body) = table
        .split_once(" = &[\n")
        .ok_or_else(|| eyre!("unsupported MT5 generated table layout"))?;
    ensure!(
        prefix
            .lines()
            .any(|line| line.starts_with("pub static SPREAD_BASELINE_MT5:")),
        "MT5 generated table declaration missing"
    );
    let body = body
        .strip_suffix("];\n")
        .ok_or_else(|| eyre!("MT5 generated table is incomplete"))?;
    let mut rows = BTreeMap::new();
    for row in body.lines().filter(|line| !line.trim().is_empty()) {
        let key = row_key(row)?;
        ensure!(
            rows.insert(key, row).is_none(),
            "duplicate MT5 table key {key}"
        );
    }
    Ok((prefix, rows))
}

fn row_key(row: &str) -> Result<&str> {
    ensure!(
        row.trim().starts_with("(\"") && row.trim().ends_with("),"),
        "unsupported MT5 generated row"
    );
    let mut fields = row.split('"');
    let feed = fields.nth(1).ok_or_else(|| eyre!("MT5 row feed missing"))?;
    let key = fields.nth(1).ok_or_else(|| eyre!("MT5 row key missing"))?;
    let (account, symbol) = key
        .strip_prefix("mt5:")
        .and_then(|key| key.split_once(':'))
        .ok_or_else(|| eyre!("invalid MT5 row key {key}"))?;
    ensure!(
        !account.is_empty() && !symbol.is_empty() && feed == format!("mt5-{account}"),
        "MT5 row feed and account key disagree"
    );
    Ok(key)
}

fn preserved_provenance(prefix: &str, account: &str) -> String {
    let mut keep = true;
    let mut comments = String::new();
    for line in prefix
        .lines()
        .take_while(|line| line.starts_with("//") || line.is_empty())
    {
        if let Some(owner) = line.strip_prefix("// @generated by bake-mt5. Account=") {
            keep = owner.split(',').next() != Some(account);
        }
        if keep {
            comments.push_str(line);
            comments.push('\n');
        }
    }
    comments
}

#[cfg(test)]
mod tests {
    use super::*;

    fn table(account: &str, symbol: &str) -> String {
        format!(
            "// @generated by bake-mt5. Account={account}, login=42, server=fixture.\n// Measured UTC window: fixture.\n#[rustfmt::skip]\npub static SPREAD_BASELINE_MT5: &[(&str, &str)] = &[\n    (\"mt5-{account}\", \"mt5:{account}:{symbol}\"),\n];\n"
        )
    }

    fn logging() {
        use tracing_subscriber::{layer::SubscriberExt, util::SubscriberInitExt};
        tracing_subscriber::registry()
            .with(tracing_subscriber::EnvFilter::from_default_env())
            .with(tracing_error::ErrorLayer::default())
            .with(tracing_subscriber::fmt::layer().with_test_writer())
            .try_init()
            .ok();
    }

    #[test]
    fn another_accounts_profiles_survive_new_bakes_and_own_replacements() {
        logging();
        let dir = tempfile::tempdir().unwrap();
        let file = dir.path().join("table.rs");
        write(&file, "competition", &table("competition", "EURUSD")).unwrap();
        write(&file, "real", &table("real", "EURUSD")).unwrap();
        write(&file, "real", &table("real", "XAUUSD")).unwrap();
        let got = std::fs::read_to_string(&file).unwrap();
        assert!(got.contains("mt5:competition:EURUSD"));
        assert!(got.contains("mt5:real:XAUUSD"));
        assert!(!got.contains("mt5:real:EURUSD"));
        assert!(got.contains("Account=competition"));
        assert!(got.contains("Account=real"));
        assert_eq!(got.matches("pub static SPREAD_BASELINE_MT5").count(), 1);
        write(&file, "real", &table("real", "XAUUSD")).unwrap();
        assert_eq!(std::fs::read_to_string(&file).unwrap(), got);
    }

    #[test]
    fn mismatched_duplicate_and_malformed_tables_preserve_existing_output() {
        logging();
        let dir = tempfile::tempdir().unwrap();
        let file = dir.path().join("table.rs");
        let original = table("competition", "EURUSD");
        write(&file, "competition", &original).unwrap();
        let duplicate = table("real", "EURUSD")
            .replace("];\n", "    (\"mt5-real\", \"mt5:real:EURUSD\"),\n];\n");
        for invalid in [table("other", "EURUSD"), duplicate, "garbage".into()] {
            assert!(write(&file, "real", &invalid).is_err());
            assert_eq!(std::fs::read_to_string(&file).unwrap(), original);
        }
    }

    #[test]
    fn an_existing_write_lock_prevents_read_modify_write_races() {
        logging();
        let dir = tempfile::tempdir().unwrap();
        let file = dir.path().join("table.rs");
        let original = table("competition", "EURUSD");
        write(&file, "competition", &original).unwrap();
        let lock = file.with_extension("rs.lock");
        std::fs::write(&lock, "other-writer").unwrap();
        assert!(write(&file, "real", &table("real", "EURUSD")).is_err());
        assert_eq!(std::fs::read_to_string(&file).unwrap(), original);
        assert_eq!(std::fs::read_to_string(lock).unwrap(), "other-writer");
    }
}
