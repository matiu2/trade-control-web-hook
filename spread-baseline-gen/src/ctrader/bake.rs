//! Promote only complete, reviewed, account-verified paired measurements.
use super::{Identity, InstrumentReport, Report};
use crate::compute::{MIN_INSTRUMENT_BARS, ReviewStatus};
use color_eyre::{Result, eyre::ensure};
use std::collections::BTreeSet;

/// Explicit partial promotion still refuses interrupted/unattempted checkpoints.
pub fn render_finished(report: &Report, identity: &Identity) -> Result<String> {
    super::checkpoint::validate(report, identity, &report.requested_symbols)?;
    let attempted = report.instruments.len() + report.failures.len();
    ensure!(
        attempted == report.requested_symbols.len(),
        "calibration has unattempted instruments; resume it first"
    );
    let eligible = report
        .instruments
        .iter()
        .filter(|r| {
            matches!(
                r.measurement.profile.review,
                ReviewStatus::Reviewed | ReviewStatus::MaskNotComputable
            )
        })
        .cloned()
        .collect::<Vec<_>>();
    let excluded = report
        .requested_symbols
        .iter()
        .filter(|s| !eligible.iter().any(|r| r.measurement.symbol == **s))
        .collect::<Vec<_>>();
    if !excluded.is_empty() {
        tracing::warn!(
            ?excluded,
            "explicit partial bake; these pairs remain uncovered, report retains the reasons"
        );
    }
    let measured = Report {
        requested_symbols: eligible
            .iter()
            .map(|r| r.measurement.symbol.clone())
            .collect(),
        instruments: eligible,
        complete: true,
        failures: vec![],
        ..report.clone()
    };
    render(&measured, identity)
}

pub fn render(report: &Report, identity: &Identity) -> Result<String> {
    identity.validate_demo()?;
    ensure!(
        report.schema_version == 1 && report.identity == *identity,
        "cTrader calibration account identity mismatch"
    );
    ensure!(
        report.source == "paired-ticks-m1",
        "cTrader spread evidence must use genuine paired M1 ticks"
    );
    ensure!(
        report.complete && report.failures.is_empty(),
        "cTrader calibration is incomplete; failures remain uncovered"
    );
    ensure!(
        report.to_utc <= chrono::Utc::now()
            && report.to_utc - report.from_utc >= chrono::Duration::days(90),
        "baking requires at least 90 closed calendar days"
    );
    let wanted = report.requested_symbols.iter().collect::<BTreeSet<_>>();
    let got = report
        .instruments
        .iter()
        .map(|r| &r.measurement.symbol)
        .collect::<BTreeSet<_>>();
    ensure!(
        !wanted.is_empty()
            && wanted.len() == report.requested_symbols.len()
            && got.len() == report.instruments.len()
            && wanted == got,
        "calibration catalogue is incomplete or duplicated"
    );
    for row in &report.instruments {
        let m = &row.measurement;
        ensure!(
            row.symbol_id > 0
                && m.first_minute_utc >= report.from_utc
                && m.last_minute_utc < report.to_utc
                && m.first_minute_utc <= m.last_minute_utc,
            "invalid cTrader measurement identity/bounds"
        );
        validate_row(m)?;
    }
    let mut rows = report.instruments.iter().collect::<Vec<_>>();
    rows.sort_by_key(|r| &r.measurement.symbol);
    let rows = rows
        .into_iter()
        .map(|row| render_row(row, &identity.profile))
        .collect::<Result<Vec<_>>>()?;
    let evidence = serde_json::to_string(identity)?;
    Ok(format!(
        "// @generated by bake-ctrader. Identity={evidence}.\n// Genuine paired M1 ticks through candle-cache, UTC {} through {}.\n#[rustfmt::skip]\n#[allow(clippy::type_complexity)]\npub static SPREAD_BASELINE_CTRADER: &[(&str, &str, &str, bool, u32, [f64; 24], f64, f64, f64, [f64; 24])] = &[\n{}];\n",
        report.from_utc,
        report.to_utc,
        rows.join("")
    ))
}
/// Revalidate the account's exact broker-native symbol/pip convention before promotion.
pub fn verify_broker_metadata(
    row: &InstrumentReport,
    id: i64,
    name: &str,
    pip_size: f64,
) -> Result<()> {
    ensure!(
        pip_size.is_finite()
            && pip_size > 0.0
            && id == row.symbol_id
            && name == row.measurement.symbol
            && pip_size == row.measurement.pip_size,
        "broker symbol identity/pip metadata changed since calibration"
    );
    Ok(())
}

fn validate_row(row: &crate::mt5::InstrumentReport) -> Result<()> {
    let symbol = &row.symbol;
    let profile = &row.profile;
    ensure!(
        !symbol.is_empty() && symbol.is_ascii() && !symbol.chars().any(char::is_control),
        "invalid symbol"
    );
    ensure!(
        matches!(
            profile.review,
            ReviewStatus::Reviewed | ReviewStatus::MaskNotComputable
        ) && profile.n_bars >= MIN_INSTRUMENT_BARS,
        "insufficient reviewed data for {symbol}"
    );
    let asset = super::asset(symbol)?;
    ensure!(
        asset.class == instrument_lookup::AssetClass::Forex,
        "cTrader spread calibration supports recognized spot FX only"
    );
    ensure!(
        asset.spread_schedule == row.schedule
            && asset.spread_schedule_tz().as_deref() == Some(row.timezone.as_str()),
        "spread schedule metadata changed for {symbol}"
    );
    ensure!(
        row.pip_size.is_finite() && row.pip_size > 0.0,
        "invalid broker-native pip size for {symbol}"
    );
    let values = profile
        .hour_widen_frac
        .iter()
        .chain(profile.hour_p90_frac.iter())
        .chain([
            &profile.baseline_low_pips,
            &profile.baseline_median_pips,
            &profile.baseline_high_pips,
        ]);
    ensure!(
        values.into_iter().all(|v| v.is_finite() && *v >= 0.0),
        "invalid spread values for {symbol}"
    );
    ensure!(
        profile.baseline_low_pips <= profile.baseline_median_pips
            && profile.baseline_median_pips <= profile.baseline_high_pips,
        "invalid spread percentiles for {symbol}"
    );
    ensure!(
        profile.elevated_hours >> 24 == 0 && profile.elevated_vec() == row.elevated_local_hours,
        "invalid hour mask for {symbol}"
    );
    ensure!(
        profile
            .hour_widen_frac
            .iter()
            .enumerate()
            .all(|(h, value)| if profile.elevated_hours & (1 << h) == 0 {
                *value == 0.0
            } else {
                *value == profile.hour_p90_frac[h]
            }),
        "widen and forecast disagree for {symbol}"
    );
    Ok(())
}

fn render_row(row: &InstrumentReport, account: &str) -> Result<String> {
    let row = &row.measurement;
    let profile = &row.profile;
    let key = format!("ctrader:{account}:{}", row.symbol);
    // JSON string escaping is also valid Rust for these checked ASCII names.
    let key = serde_json::to_string(&key)?;
    let schedule = serde_json::to_string(&row.schedule)?;
    Ok(format!(
        "    (\"ctrader-{account}\", {key}, {schedule}, true, {}, {:?}, {:?}, {:?}, {:?}, {:?}),\n",
        profile.elevated_hours,
        profile.hour_widen_frac,
        profile.baseline_median_pips,
        profile.baseline_low_pips,
        profile.baseline_high_pips,
        profile.hour_p90_frac
    ))
}

