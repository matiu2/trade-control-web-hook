//! Recognize canonical baker output before preserving its literal row bytes.
use crate::ctrader::Identity;
use color_eyre::{
    Result,
    eyre::{ensure, eyre},
};
use std::collections::BTreeSet;

const DECLARATION: &str = "pub static SPREAD_BASELINE_CTRADER: &[(&str, &str, &str, bool, u32, [f64; 24], f64, f64, f64, [f64; 24])] = &[";

pub(super) struct Table<'a> {
    pub identity: Identity,
    pub window: &'a str,
    pub rows: Vec<Row<'a>>,
    pub insert_at: usize,
}

pub(super) struct Row<'a> {
    pub key: String,
    pub line: &'a str,
}

pub(super) fn parse(source: &str) -> Result<Table<'_>> {
    let lines = source.lines().collect::<Vec<_>>();
    ensure!(
        lines.len() >= 7
            && lines[1].starts_with("// Genuine paired M1 ticks through candle-cache, UTC ")
            && lines[2] == "#[rustfmt::skip]"
            && lines[3] == "#[allow(clippy::type_complexity)]"
            && lines[4] == DECLARATION
            && source.ends_with("\n];\n"),
        "additive cTrader bake requires canonical generated table format"
    );
    let identity = lines[0]
        .strip_prefix("// @generated by bake-ctrader. Identity=")
        .and_then(|line| line.strip_suffix('.'))
        .ok_or_else(|| eyre!("existing cTrader table has no verified identity header"))?;
    let identity: Identity = serde_json::from_str(identity)?;
    identity.validate_demo()?;
    let rows = lines[5..lines.len() - 1]
        .iter()
        .map(|line| row(line, &identity.profile))
        .collect::<Result<Vec<_>>>()?;
    ensure!(
        !rows.is_empty()
            && rows
                .iter()
                .map(|row| &row.key)
                .collect::<BTreeSet<_>>()
                .len()
                == rows.len(),
        "additive cTrader bake refuses empty or duplicate rows"
    );
    let insert_at = source
        .rfind("\n];\n")
        .ok_or_else(|| eyre!("missing cTrader table terminator"))?
        + 1;
    Ok(Table {
        identity,
        window: lines[1],
        rows,
        insert_at,
    })
}

fn row<'a>(line: &'a str, account: &str) -> Result<Row<'a>> {
    let body = line
        .trim_start()
        .strip_prefix('(')
        .ok_or_else(|| eyre!("invalid cTrader generated row"))?;
    let (provider, rest) = quoted(body)?;
    let rest = rest
        .trim_start()
        .strip_prefix(',')
        .ok_or_else(|| eyre!("invalid cTrader row separator"))?
        .trim_start();
    let (key, rest) = quoted(rest)?;
    let prefix = format!("ctrader:{account}:");
    let symbol = key
        .strip_prefix(&prefix)
        .ok_or_else(|| eyre!("cTrader generated row belongs to another account"))?;
    ensure!(
        provider == format!("ctrader-{account}")
            && !symbol.is_empty()
            && symbol.is_ascii()
            && !symbol.chars().any(char::is_control)
            && rest.trim_start().starts_with(',')
            && line.trim_end().ends_with("),"),
        "invalid cTrader generated account row"
    );
    Ok(Row { key, line })
}

fn quoted(source: &str) -> Result<(String, &str)> {
    let mut decoder = serde_json::Deserializer::from_str(source).into_iter::<String>();
    let value = decoder
        .next()
        .transpose()?
        .ok_or_else(|| eyre!("missing cTrader row string"))?;
    Ok((value, &source[decoder.byte_offset()..]))
}
